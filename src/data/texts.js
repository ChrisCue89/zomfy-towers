/** »a, b und c« – Aufzählung im Satz (M25: drei Wege lasen sich als »a und b und c«). */
function liste(items) {
  if (items.length <= 1) return items[0] || '';
  return `${items.slice(0, -1).join(', ')} und ${items[items.length - 1]}`;
}

