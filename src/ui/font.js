export const LINE_HEIGHT = 12;
export const GLYPH_ROWS = 11;
const SPACE_WIDTH = 3;
const SPACING = 1;

const glyphs = new Map();
for (const [ch, [top, ...rows]] of Object.entries(GLYPHS)) {
  const width = rows[0].length;
  const pixels = [];
  rows.forEach((row, i) => {
    for (let x = 0; x < row.length; x++) if (row[x] === '#') pixels.push([x, top + i]);
  });
  glyphs.set(ch, { width, pixels });
}
glyphs.set(' ', { width: SPACE_WIDTH, pixels: [] });
const FALLBACK = glyphs.get('?');

/** Liefert alle Zeichen, die die Schrift nicht kennt (für Tests). */
export function missingGlyphs(text) {
  const missing = new Set();
  for (const ch of text) if (!glyphs.has(ch) && ch !== '\n') missing.add(ch);
  return [...missing];
}

function glyph(ch) {
  return glyphs.get(ch) || FALLBACK;
}

// Name der Hauptfigur (Meilenstein 7): Die Texte sagen »Mika«, gezeigt wird der
// gewählte Name – beim Messen, Umbrechen und Zeichnen gleich.
let playerName = null;
export function setPlayerName(name) {
  playerName = name && name !== 'Mika' ? name : null;
}
const named = (text) => (playerName && text.includes('Mika') ? text.replaceAll('Mika', playerName) : text);

export function measure(text) {
  text = named(text);
  let width = 0;
  let first = true;
  for (const ch of text) {
    if (!first) width += SPACING;
    width += glyph(ch).width;
    first = false;
  }
  return width;
}

/** Zeilenumbruch nach Wörtern. Harte Umbrüche mit \n. */
export function wrap(text, maxWidth) {
  text = named(text);
  const lines = [];
  for (const paragraph of text.split('\n')) {
    let line = '';
    for (const word of paragraph.split(' ')) {
      const candidate = line ? `${line} ${word}` : word;
      if (measure(candidate) <= maxWidth || !line) line = candidate;
      else {
        lines.push(line);
        line = word;
      }
    }
    lines.push(line);
  }
  return lines;
}

// Atlas je Farbe: Glyphen einmal in ein Offscreen-Canvas zeichnen.
const atlases = new Map();
const CELL_W = 8;
const COLUMNS = 16;
const order = [...glyphs.keys()];
const indexOf = new Map(order.map((ch, i) => [ch, i]));

function atlasFor(color) {
  if (atlases.has(color)) return atlases.get(color);
  const rows = Math.ceil(order.length / COLUMNS);
  const canvas = document.createElement('canvas');
  canvas.width = COLUMNS * CELL_W;
  canvas.height = rows * GLYPH_ROWS;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = color;
  order.forEach((ch, i) => {
    const ox = (i % COLUMNS) * CELL_W;
    const oy = Math.floor(i / COLUMNS) * GLYPH_ROWS;
    for (const [x, y] of glyphs.get(ch).pixels) ctx.fillRect(ox + x, oy + y, 1, 1);
  });
  atlases.set(color, canvas);
  return canvas;
}

/**
 * Text zeichnen. (x, y) = linke obere Ecke der Zeile (Zeile 0 des Rasters).
 * @param {CanvasRenderingContext2D} ctx
 */
export function drawText(ctx, text, x, y, color, { shadow = null, outline = null } = {}) {
  text = named(text);
  x = Math.round(x);
  y = Math.round(y);
  if (outline) {
    for (const [dx, dy] of [[-1, 0], [1, 0], [0, -1], [0, 1]]) drawText(ctx, text, x + dx, y + dy, outline);
  }
  if (shadow) drawText(ctx, text, x + 1, y + 1, shadow);
  const atlas = atlasFor(color);
  let cx = x;
  for (const ch of text) {
    const g = glyph(ch);
    const i = indexOf.get(glyphs.has(ch) ? ch : '?');
    if (g.pixels.length) {
      ctx.drawImage(atlas, (i % COLUMNS) * CELL_W, Math.floor(i / COLUMNS) * GLYPH_ROWS, g.width, GLYPH_ROWS, cx, y, g.width, GLYPH_ROWS);
    }
    cx += g.width + SPACING;
  }
  return cx - x - SPACING;
}

/** Mehrzeiligen, umbrochenen Text zeichnen; gibt die Höhe zurück. */
export function drawWrapped(ctx, text, x, y, maxWidth, color, options) {
  const lines = wrap(text, maxWidth);
  lines.forEach((line, i) => drawText(ctx, line, x, y + i * LINE_HEIGHT, color, options));
  return lines.length * LINE_HEIGHT;
}

