/** Kleine Zahl zeichnen (3×5-Ziffern, 1 px Abstand). */
export function drawTiny(ctx, text, x, y, color) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  for (const ch of String(text)) {
    const rows = TINY[ch];
    if (rows) {
      rows.forEach((row, ry) => {
        for (let rx = 0; rx < 3; rx++) if (row[rx] === '#') ctx.fillRect(cx + rx, Math.round(y) + ry, 1, 1);
      });
    }
    cx += 4;
  }
}
